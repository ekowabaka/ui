import path from 'path';
import { fileURLToPath } from 'url';
import MiniCssExtractPlugin from 'mini-css-extract-plugin';
import TerserPlugin from 'terser-webpack-plugin';
import CssMinimizerPlugin from 'css-minimizer-webpack-plugin';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const sharedRules = [
  // 1. Global SASS in sass/ directory -> compiled and extracted
  {
    test: /\.s[ac]ss$/i,
    include: path.resolve(__dirname, 'sass'),
    use: [
      MiniCssExtractPlugin.loader,
      'css-loader',
      'sass-loader',
    ],
  },
  // 2. Component styles in js/ directory -> loaded as raw strings for Shadow DOM
  {
    test: /\.(s[ac]ss|css)$/i,
    include: path.resolve(__dirname, 'js'),
    use: [
      'to-string-loader',
      {
        loader: 'css-loader',
        options: {
          esModule: false,
        },
      },
      'sass-loader',
    ],
  },
];

const cssEntries = {
  'css/core': './sass/core.scss',
  'css/forms': './sass/forms.scss',
  'css/buttons': './sass/buttons.scss',
  'css/menus': './sass/menus.scss',
  'css/cards': './sass/cards.scss',
  'css/dropdowns': './sass/dropdowns.scss',
  'css/tables': './sass/tables.scss',
};

// Suppress empty .js chunks generated by Webpack for CSS-only entry points
const removeCssEntryJsPlugin = {
  apply(compiler) {
    compiler.hooks.compilation.tap('RemoveCssEntryJsPlugin', (compilation) => {
      compilation.hooks.processAssets.tap(
        {
          name: 'RemoveCssEntryJsPlugin',
          stage: compiler.webpack.Compilation.PROCESS_ASSETS_STAGE_ADDITIONAL,
        },
        (assets) => {
          for (const name of Object.keys(assets)) {
            if (name.startsWith('css/') && name.endsWith('.js')) {
              compilation.deleteAsset(name);
            }
          }
        }
      );
    });
  },
};

const unminifiedConfig = {
  mode: 'production',
  devtool: false,
  entry: {
    fzui: './js/fzui.js',
    ...cssEntries,
  },
  output: {
    path: path.resolve(__dirname, 'dist'),
    filename: '[name].js',
    library: {
      name: 'fzui',
      type: 'umd',
    },
    globalObject: 'typeof self !== "undefined" ? self : this',
    clean: true,
  },
  optimization: {
    minimize: false,
  },
  module: {
    rules: sharedRules,
  },
  plugins: [
    new MiniCssExtractPlugin({
      filename: '[name].css',
      chunkFilename: '[name].css',
    }),
    removeCssEntryJsPlugin,
  ],
};

const minifiedConfig = {
  mode: 'production',
  devtool: false,
  entry: {
    fzui: './js/fzui.js',
    ...cssEntries,
  },
  output: {
    path: path.resolve(__dirname, 'dist'),
    filename: '[name].min.js',
    library: {
      name: 'fzui',
      type: 'umd',
    },
    globalObject: 'typeof self !== "undefined" ? self : this',
    clean: false,
  },
  optimization: {
    minimize: true,
    minimizer: [
      new TerserPlugin({
        extractComments: false,
      }),
      new CssMinimizerPlugin(),
    ],
  },
  module: {
    rules: sharedRules,
  },
  plugins: [
    new MiniCssExtractPlugin({
      filename: '[name].min.css',
      chunkFilename: '[name].min.css',
    }),
    removeCssEntryJsPlugin,
  ],
};

export default [unminifiedConfig, minifiedConfig];
